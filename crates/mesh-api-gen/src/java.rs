//! Generated Java marshalling for API methods.
//!
//! One self-contained `.java` file per API document: numeric component,
//! method, and field tags; a minimal definite-length CBOR runtime; the tagged
//! record envelope; typed request/response classes with `encode`/`decode`;
//! per-method handler interfaces; and per-component dispatch that routes a
//! decoded request record to a handler and encodes the correlated response.
//!
//! Wire contract (matches `mesh::cbor::encode_record` and the firmware
//! canonical form):
//!
//! - requests: map keys `1` component, `2` method (uint tags or text names),
//!   `3` id, `5` field map (uint field tag -> value), `9` `to`, `10` bytes;
//! - responses: `3` id plus `6` result or `7` error, where typed results are
//!   maps of uint field tag to value;
//! - CBOR integers decode to Java `Long`, doubles to `Double`, and field map
//!   keys stay `Long` tags or `String` names.
//!
//! Methods without numeric identities still generate typed classes using
//! name-based envelopes, but dispatch requires numeric identities.

use std::fmt::Write as _;

use crate::{ApiField, ApiMethod};

/// Render one deterministic Java source file for the given methods.
pub fn java_api(methods: &[ApiMethod], package: Option<&str>, class_name: &str) -> String {
    let mut output = String::from("// Generated by mesh-api-gen from API.md; do not edit.\n\n");
    if let Some(package) = package {
        let _ = writeln!(output, "package {package};\n");
    }
    output.push_str("import java.util.List;\n");
    if package != Some("com.github.costinm.dmesh") {
        output.push_str("import com.github.costinm.dmesh.Envelope;\n");
    }
    output.push('\n');
    let _ = writeln!(
        output,
        "/**\n * Generated tagged-CBOR types, numeric identities, and dispatch for\n\
         \x20* `{class_name}` APIs. Marshal whole frames as `byte[]`; no runtime\n\
         \x20* schema or catalog is required.\n\
         \x20*/"
    );
    let _ = writeln!(output, "public final class {class_name} {{");
    let _ = writeln!(output, "    private {class_name}() {{}}\n");

    render_identities(&mut output, methods);
    for component in components(methods) {
        render_handler_interfaces(&mut output, &component);
        render_dispatcher(&mut output, &component);
    }
    for method in methods {
        render_record_class(&mut output, method, "request");
        render_record_class(&mut output, method, "response");
    }

    output.push_str("}\n");
    output
}

struct ComponentGroup {
    name: String,
    index: Option<u32>,
    methods: Vec<ApiMethod>,
}

fn components(methods: &[ApiMethod]) -> Vec<ComponentGroup> {
    let mut groups: Vec<ComponentGroup> = Vec::new();
    for method in methods {
        match groups
            .iter_mut()
            .find(|group| group.name == method.component)
        {
            Some(group) => group.methods.push(method.clone()),
            None => groups.push(ComponentGroup {
                name: method.component.clone(),
                index: method.component_index,
                methods: vec![method.clone()],
            }),
        }
    }
    groups
}

fn render_identities(output: &mut String, methods: &[ApiMethod]) {
    let mut seen_components: Vec<(String, u32)> = Vec::new();
    for method in methods {
        if let Some(index) = method.component_index
            && !seen_components
                .iter()
                .any(|(name, _)| name == &method.component)
        {
            seen_components.push((method.component.clone(), index));
        }
    }
    if !seen_components.is_empty() {
        output.push_str("    /** Numeric component tags. */\n");
        for (name, index) in &seen_components {
            let _ = writeln!(
                output,
                "    public static final int COMPONENT_{} = {index};",
                crate::identifier(name)
            );
        }
        output.push('\n');
    }

    let tagged: Vec<&ApiMethod> = methods
        .iter()
        .filter(|method| method.method_index.is_some())
        .collect();
    if !tagged.is_empty() {
        output.push_str("    /** Numeric method tags. */\n");
        for method in &tagged {
            let _ = writeln!(
                output,
                "    public static final int METHOD_{} = {};",
                crate::identifier(&format!("{}_{}", method.component, method.method)),
                method.method_index.expect("filtered method index")
            );
        }
        output.push('\n');
    }
}

fn type_class(method: &ApiMethod, shape: &str) -> String {
    format!(
        "{}{}{}",
        crate::pascal_identifier(&method.component),
        crate::pascal_identifier(&method.method),
        if shape == "request" {
            "Request"
        } else {
            "Response"
        }
    )
}

fn shape_fields<'a>(method: &'a ApiMethod, shape: &str) -> &'a [ApiField] {
    if shape == "request" {
        &method.request.fields
    } else {
        &method.response.fields
    }
}

/// Lower-camel Java identifier for an API field name.
fn java_field(value: &str) -> String {
    let camel = crate::pascal_identifier(value);
    let mut characters = camel.chars();
    match characters.next() {
        Some(first) => {
            let lowered = first.to_ascii_lowercase();
            let name = format!("{lowered}{}", characters.as_str());
            if java_reserved().contains(&name.as_str()) {
                format!("{name}_")
            } else {
                name
            }
        }
        None => String::new(),
    }
}

