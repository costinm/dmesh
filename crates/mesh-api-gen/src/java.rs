/// Java type for one API field type. Returns `(type, is_primitive)`.
fn java_type(value_type: &str, required: bool) -> (String, bool) {
    if let Some(item) = value_type.strip_suffix("[]") {
        let (item_type, _) = java_type(item, true);
        return (format!("List<{item_type}>"), false);
    }
    let (base, primitive) = match value_type {
        "bool" => ("boolean", true),
        "u8" | "u16" | "u32" | "i8" | "i16" | "i32" => ("int", true),
        "u64" | "i64" => ("long", true),
        "f32" => ("float", true),
        "f64" => ("double", true),
        "string" => ("String", false),
        "bytes" => ("byte[]", false),
        _ => ("Object", false),
    };
    if required || !primitive {
        (base.to_owned(), primitive)
    } else {
        (boxed(base).to_owned(), false)
    }
}

fn boxed(primitive: &str) -> &'static str {
    match primitive {
        "boolean" => "Boolean",
        "int" => "Integer",
        "long" => "Long",
        "float" => "Float",
        "double" => "Double",
        other => unreachable!("no boxed form registered for {other}"),
    }
}

/// Conversion expression reading one typed field from an `Object` decoded
/// from CBOR, assigned into `<receiver>.<field>`.
fn decode_expression(field: &ApiField, receiver: &str) -> String {
    let target = java_field(&field.name);
    let assignment = if let Some(item) = field.value_type.strip_suffix("[]") {
        let helper = match item {
            "u8" | "u16" | "u32" | "i8" | "i16" | "i32" => "asIntList",
            "u64" | "i64" => "asLongList",
            "f64" => "asDoubleList",
            "string" => "asStringList",
            _ => "asList",
        };
        format!("{target} = Envelope.{helper}(value);")
    } else {
        let expression = match field.value_type.as_str() {
            "bool" => "(Boolean) value".to_owned(),
            "u8" | "u16" | "u32" | "i8" | "i16" | "i32" => "((Number) value).intValue()".to_owned(),
            "u64" | "i64" => "((Number) value).longValue()".to_owned(),
            "f32" => "((Number) value).floatValue()".to_owned(),
            "f64" => "((Number) value).doubleValue()".to_owned(),
            "string" => "(String) value".to_owned(),
            "bytes" => "(byte[]) value".to_owned(),
            _ => "value".to_owned(),
        };
        format!("{target} = {expression};")
    };
    format!("{receiver}.{assignment}")
}

fn render_record_class(output: &mut String, method: &ApiMethod, shape: &str) {
    let class = type_class(method, shape);
    let fields = shape_fields(method, shape);
    let kind_word = if shape == "request" {
        "request"
    } else {
        "response"
    };
    let _ = writeln!(
        output,
        "    /** {} */",
        if method.summary.is_empty() {
            format!("Generated tagged-CBOR {kind_word} for `{}`.", method.id)
        } else {
            format!(
                "Generated tagged-CBOR {kind_word} for `{}`: {}",
                method.id, method.summary
            )
        }
    );
    let _ = writeln!(output, "    public static final class {class} {{");

    if !fields.is_empty() {
        output.push_str("        /** Numeric field tags. */\n");
        for field in fields {
            let _ = writeln!(
                output,
                "        public static final int FIELD_{} = {};",
                crate::identifier(&field.name),
                field.index
            );
        }
        output.push('\n');
    }

    for field in fields {
        if let Some(default) = &field.default {
            let _ = writeln!(
                output,
                "        /** API field `{}` (default {}). */",
                field.name, default
            );
        } else {
            let _ = writeln!(output, "        /** API field `{}`. */", field.name);
        }
        let (java, _) = java_type(&field.value_type, field.required);
        let _ = writeln!(
            output,
            "        public {java} {};\n",
            java_field(&field.name)
        );
    }

    if shape == "request" {
        let _ = writeln!(
            output,
            "        /** Encode a correlated tagged-CBOR {kind_word} envelope for this method. */"
        );
        let _ = writeln!(output, "        public Envelope encode(Object id) {{");
        output.push_str("            Envelope envelope = new Envelope();\n");
        match method.component_index {
            Some(index) => {
                let _ = index;
                let _ = writeln!(
                    output,
                    "            envelope.componentTag = (long) COMPONENT_{};",
                    crate::identifier(&method.component)
                );
                let _ = writeln!(
                    output,
                    "            envelope.methodTag = (long) METHOD_{};",
                    crate::identifier(&format!("{}_{}", method.component, method.method))
                );
            }
            None => {
                let _ = writeln!(
                    output,
                    "            envelope.componentName = \"{}\";",
                    method.component
                );
                let _ = writeln!(
                    output,
                    "            envelope.methodName = \"{}\";",
                    method.method
                );
            }
        }
        output.push_str("            envelope.id = id;\n");
        for field in fields {
            let target = java_field(&field.name);
            let key = format!("FIELD_{}", crate::identifier(&field.name));
            if field.required {
                let _ = writeln!(output, "            envelope.putField({key}, {target});");
            } else {
                let _ = writeln!(
                    output,
                    "            if ({target} != null) envelope.putField({key}, {target});"
                );
            }
        }
        output.push_str("            return envelope;\n        }\n\n");
        let _ = writeln!(
            output,
            "        /** Decode the typed {kind_word} from an envelope. */"
        );
        let _ = writeln!(
            output,
            "        public static {class} decode(Envelope envelope) {{"
        );
        let _ = writeln!(output, "            {class} request = new {class}();");
        for field in fields {
            let _ = writeln!(
                output,
                "            {{\n                Object value = envelope.getField(FIELD_{});\n                if (value != null) {};\n            }}",
                crate::identifier(&field.name),
                decode_expression(field, "request")
            );
        }
        output.push_str("            return request;\n        }\n");
    } else {
        let _ = writeln!(
            output,
            "        /** Encode the correlated tagged-CBOR response with a numeric result map. */"
        );
        let _ = writeln!(output, "        public Envelope encode(Object id) {{");
        output.push_str("            Envelope envelope = new Envelope();\n");
        match method.component_index {
            Some(index) => {
                let _ = index;
                let _ = writeln!(
                    output,
                    "            envelope.componentTag = (long) COMPONENT_{};",
                    crate::identifier(&method.component)
                );
                let _ = writeln!(
                    output,
                    "            envelope.methodTag = (long) METHOD_{};",
                    crate::identifier(&format!("{}_{}", method.component, method.method))
                );
            }
            None => {
                let _ = writeln!(
                    output,
                    "            envelope.componentName = \"{}\";",
                    method.component
                );
                let _ = writeln!(
                    output,
                    "            envelope.methodName = \"{}\";",
                    method.method
                );
            }
        }
        output.push_str("            envelope.id = id;\n");
        for field in fields {
            let target = java_field(&field.name);
            let key = format!("FIELD_{}", crate::identifier(&field.name));
            if field.required {
                let _ = writeln!(
                    output,
                    "            envelope.putResultField({key}, {target});"
                );
            } else {
                let _ = writeln!(
                    output,
                    "            if ({target} != null) envelope.putResultField({key}, {target});"
                );
            }
        }
        output.push_str("            return envelope;\n        }\n\n");
        let _ = writeln!(
            output,
            "        /** Decode the typed response from an envelope. */"
        );
        let _ = writeln!(
            output,
            "        public static {class} decode(Envelope envelope) {{"
        );
        let _ = writeln!(output, "            {class} response = new {class}();");
        for field in fields {
            let _ = writeln!(
                output,
                "            {{\n                Object value = envelope.getResultField(FIELD_{});\n                if (value != null) {};\n            }}",
                crate::identifier(&field.name),
                decode_expression(field, "response")
            );
        }
        output.push_str("            return response;\n        }\n");
    }
    output.push_str("    }\n\n");
}

fn render_handler_interfaces(output: &mut String, component: &ComponentGroup) {
    let Some(_) = component.index else {
        return;
    };
    output.push_str("    // Handler interfaces\n");
    for method in &component.methods {
        let Some(method_index) = method.method_index else {
            continue;
        };
        let _ = method_index;
        let interface = format!(
            "{}{}Handler",
            crate::pascal_identifier(&component.name),
            crate::pascal_identifier(&method.method)
        );
        let request = type_class(method, "request");
        let response = type_class(method, "response");
        let summary = if method.summary.is_empty() {
            format!("Handle `{}`.", method.id)
        } else {
            format!("{} Handles `{}`.", method.summary, method.id)
        };
        let _ = writeln!(output, "    /** {summary} */");
        let _ = writeln!(output, "    public interface {interface} {{");
        let _ = writeln!(
            output,
            "        {response} {}({request} request) throws Exception;",
            java_field(&method.method)
        );
        output.push_str("    }\n\n");
    }
}

fn render_dispatcher(output: &mut String, component: &ComponentGroup) {
    let Some(component_index) = component.index else {
        return;
    };
    let component_constant = crate::identifier(&component.name);
    let component_class = crate::pascal_identifier(&component.name);
    let _ = writeln!(
        output,
        "    /** Dispatch a tagged request for the `{}` component. */",
        component.name
    );
    let _ = writeln!(output, "    public static final class {component_class} {{");
    let _ = writeln!(output, "        private {component_class}() {{}}\n");
    output.push_str(
        "        /** Dispatch one decoded request record to a handler that implements\n\
         \x20        * the addressed method, encoding the correlated response. Returns\n\
         \x20        * `null` when the handler produced no response. */\n",
    );
    let _ = writeln!(
        output,
        "        public static Envelope dispatch(Envelope request, Object handler) throws Exception {{"
    );
    output.push_str(
        "            if (request == null || request.methodTag == null) throw new IllegalArgumentException(\"dispatch requires a tagged request record\");\n",
    );
    let _ = writeln!(
        output,
        "            if (request.componentTag == null || request.componentTag.longValue() != COMPONENT_{component_constant}) throw new IllegalArgumentException(\"record is not for the {} component\");",
        component.name
    );
    output.push_str("            long method = request.methodTag.longValue();\n");
    for method in &component.methods {
        let Some(_) = method.method_index else {
            continue;
        };
        let interface = format!(
            "{}{}Handler",
            crate::pascal_identifier(&component.name),
            crate::pascal_identifier(&method.method)
        );
        let method_constant = crate::identifier(&format!("{}_{}", method.component, method.method));
        let request = type_class(method, "request");
        let response = type_class(method, "response");
        let _ = writeln!(
            output,
            "            if (method == METHOD_{method_constant} && handler instanceof {interface}) {{"
        );
        let _ = writeln!(
            output,
            "                {response} response = (({interface}) handler).{}({request}.decode(request));",
            java_field(&method.method)
        );
        output.push_str(
            "                return response == null ? null : response.encode(request.id);\n",
        );
        output.push_str("            }\n");
    }
    let _ = writeln!(
        output,
        "            throw new UnsupportedOperationException(\"no handler for {} method \" + method);",
        component.name
    );
    let _ = component_index;
    output.push_str("        }\n    }\n\n");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_deterministic_java_from_fixture() {
        let methods = crate::parse_api_markdown(include_str!("../API.md")).unwrap();
        let first = java_api(&methods, Some("com.example.gen"), "MeshApi");
        let second = java_api(&methods, Some("com.example.gen"), "MeshApi");
        assert_eq!(first, second);
        assert!(first.contains("package com.example.gen;"));
        assert!(first.contains("public static final int COMPONENT_FULL = 3;"));
        assert!(first.contains("public static final int METHOD_FULL_INITIALIZE = 1;"));
        assert!(first.contains("public static final class FullInitializeRequest"));
        assert!(first.contains("public static final class FullInitializeResponse"));
        assert!(first.contains("public interface FullInitializeHandler"));
        assert!(first.contains("public static final class Full"));
        // Host-only component: typed classes exist, dispatcher does not.
        assert!(first.contains("HostDiagnosticsVersionRequest"));
        assert!(!first.contains("COMPONENT_HOST_DIAGNOSTICS"));
    }

    #[test]
    fn generated_request_round_trips_through_record() {
        // Encoding behavior is exercised by compiling and running the Java
        // output; here assert the generated encode path uses the documented
        // envelope keys and numeric identities.
        let methods = crate::parse_api_markdown(include_str!("../API.md")).unwrap();
        let output = java_api(&methods, None, "MeshApi");
        assert!(output.contains("envelope.componentTag = (long) COMPONENT_FULL;"));
        assert!(output.contains("envelope.methodTag = (long) METHOD_FULL_ECHO;"));
        assert!(output.contains("if (value != null) envelope.putField(FIELD_VALUE, value);"));
        assert!(output.contains("envelope.putResultField(FIELD_VALUE, value);"));
    }
}
